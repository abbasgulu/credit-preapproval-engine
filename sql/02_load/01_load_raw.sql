-- =====================================================================
-- 01_load_raw.sql
-- Loads every CSV into its raw table: ext_* (text) -> raw_* (typed).
--
-- For each table:
--   1. TRUNCATE       - makes the script safe to re-run
--   2. p_load_start   - writes a RUNNING row to raw_load_log
--   3. INSERT APPEND  - direct-path insert with explicit type conversion
--   4. p_load_end     - counts rows; stops the run on any mismatch
--
-- Small tables first: a problem shows up in seconds, not after 27M rows.
-- =====================================================================

WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET TIMING ON
SET FEEDBACK ON

-- CSV numbers use '.' as the decimal separator, whatever the Windows locale is
ALTER SESSION SET NLS_NUMERIC_CHARACTERS = '.,';

